import crypto from 'node:crypto';
import {canonicalJson,IntakeError} from './intake-store.mjs';
import {productPhotoPlan} from './product-photo-plan.mjs';
import {photoSourceForSlot} from './product-gallery.mjs';
import {importProductPilot} from './product-pilot-import.mjs';

const object=value=>value!==null&&typeof value==='object'&&!Array.isArray(value);
const sha=value=>crypto.createHash('sha256').update(canonicalJson(value)).digest('hex');
const equal=(left,right)=>canonicalJson(left)===canonicalJson(right);
const fail=code=>{throw new IntakeError(code,422);};
const references=items=>items.map(({id,sha256})=>({id,sha256}));
const slotIdentity=slot=>({id:slot.id,role:slot.role,...(slot.visualUnitId?{visualUnitId:slot.visualUnitId}:{})});

// Trusted local orchestration only. This binds the exact prompt and ordered
// references to a saved plan; it does not call a provider, inspect source bytes,
// certify product fidelity or prove provider billing. importProductPilot still
// checks the original and generated bytes inside its serialized transaction.
export function preparePhotoExecution(record,packet,{slotId,operatorAugmentation=''}={}){
  if(!object(packet)||packet.kind!=='photos'||!Array.isArray(packet.slots)||!Array.isArray(packet.assetEvidence))fail('PHOTO_EXECUTION_PACKET_INVALID');
  if(record.order?.status!=='verified_paid')fail('PAYMENT_REQUIRED');
  if(packet.projectId!==record.id||packet.ownerId!==record.ownerId||packet.orderId!==record.order.id)fail('PHOTO_EXECUTION_OWNER_MISMATCH');
  const saved=record.productPilotPackets?.[packet.packetId];
  const {packetId,payloadHash,preparedAt,...content}=packet;
  if(!saved||!equal(saved,packet)||sha(content)!==payloadHash)fail('PHOTO_EXECUTION_PACKET_CHANGED');
  if(typeof slotId!=='string'||!slotId||typeof operatorAugmentation!=='string'||operatorAugmentation.length>8000)fail('PHOTO_EXECUTION_INPUT_INVALID');

  const state=record.productTasks?.[packet.productId],work=state?.submission&&record.jobs[`${state.submission.hash}:work`];
  if(work?.status!=='succeeded'||work.result?.output?.delivery!=='product_photo_plan'||!work.inputs)fail('PHOTO_EXECUTION_PLAN_PENDING');
  const plan=productPhotoPlan(record,packet.productId);
  if(sha(plan)!==work.result.hash||!equal(plan,work.result.output))fail('PHOTO_EXECUTION_PLAN_CHANGED');
  if(packet.workId!==`${state.submission.hash}:work`)fail('PHOTO_EXECUTION_PLAN_CHANGED');

  const gallery=record.productGalleries?.[packet.productId];
  if(!gallery||gallery.sourceHash!==packet.sourceHash||sha(work.inputs)!==packet.sourceHash||!equal(gallery.source,work.inputs))fail('PHOTO_EXECUTION_SOURCE_CHANGED');
  const plannedSlots=plan.slots.filter(slot=>(slot.visualUnitId??null)===(packet.visualUnitId??null));
  if(!plannedSlots.length||!equal(packet.slots,plannedSlots.map(slotIdentity)))fail('PHOTO_EXECUTION_SLOTS_CHANGED');
  const slot=plannedSlots.find(item=>item.id===slotId),gallerySlot=gallery.slots.find(item=>item.id===slotId);
  if(!slot||!gallerySlot||!equal(slotIdentity(slot),slotIdentity(gallerySlot)))fail('PHOTO_EXECUTION_SLOT_CHANGED');
  // Order is material: the first reference is the primary view in the prompt.
  if(!equal(references(packet.assetEvidence),slot.sources)||!equal(packet.source,photoSourceForSlot(gallery,slotId)))fail('PHOTO_EXECUTION_SOURCE_CHANGED');

  const prompt=operatorAugmentation?`${slot.prompt}\n${operatorAugmentation}`:slot.prompt;
  const specification={schemaVersion:1,delivery:'product_photo_execution',projectId:record.id,productId:packet.productId,
    visualUnitId:packet.visualUnitId??null,slotId:slot.id,role:slot.role,packetId:packet.packetId,packetHash:packet.payloadHash,
    sourceHash:packet.sourceHash,planHash:work.result.hash,promptVersion:plan.promptVersion,promptHash:slot.promptHash,
    basePrompt:slot.prompt,sources:structuredClone(slot.sources),operatorAugmentation,prompt,
    executionPromptHash:sha({prompt,sources:slot.sources})};
  return {...specification,specHash:sha(specification)};
}

// Call immediately before trusted import, with the current stored record. A
// replay may revalidate after the initial candidate exists; this function never
// spends or reserves a regeneration allowance or edits gallery selection.
export function validatePhotoExecution(record,packet,specification){
  if(!object(specification))fail('PHOTO_EXECUTION_SPEC_INVALID');
  const current=preparePhotoExecution(record,packet,{slotId:specification.slotId,operatorAugmentation:specification.operatorAugmentation});
  if(!equal(current,specification))fail('PHOTO_EXECUTION_SPEC_CHANGED');
  return current;
}

// The plan, original/output bytes, candidate, receipt and prompt provenance are
// checked and committed under one TaskStore transaction. The inner adapter
// reuses that record instead of acquiring the same lock a second time.
export async function importPlannedPhoto(store,session,{packet,specification,result,evidence}){
  return store.transact(session.projectId,session.ownerId,async record=>{
    const verified=validatePhotoExecution(record,packet,specification);
    if(!object(result)||result.slotId!==verified.slotId)fail('PHOTO_EXECUTION_RESULT_SLOT_MISMATCH');
    const provenance={specHash:verified.specHash,planHash:verified.planHash,promptHash:verified.promptHash,
      executionPromptHash:verified.executionPromptHash,sources:structuredClone(verified.sources),
      outputSha256:result.sha256,executionId:evidence?.executionId};
    const key=`${packet.packetId}:${result.slotId}`,prior=record.productPilotImports?.[key];
    if(prior){
      const asset=record.generatedAssets?.[prior.delivered?.assetId];
      if(!equal(prior.photoExecution,provenance)||!equal(asset?.photoExecution,provenance)||asset?.sha256!==provenance.outputSha256)fail('PHOTO_EXECUTION_PROVENANCE_CONFLICT');
    }
    const transactionStore={directory:store.directory.bind(store),transact:async(id,owner,operation)=>{
      if(id!==record.id||owner!==record.ownerId)fail('PHOTO_EXECUTION_OWNER_MISMATCH');
      return {record,result:await operation(record)};
    }};
    const imported=await importProductPilot(transactionStore,session,{packet,result,evidence});
    const receipt=record.productPilotImports[key],asset=record.generatedAssets[receipt.delivered.assetId];
    if(!imported.result.duplicate){
      receipt.photoExecution=structuredClone(provenance);asset.photoExecution=structuredClone(provenance);
    }
    return {duplicate:imported.result.duplicate,receipt:structuredClone(receipt)};
  });
}
